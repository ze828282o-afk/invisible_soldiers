// ---------- live search / filter ----------
const searchInput = document.getElementById('searchInput');
const noResults = document.getElementById('noResults');
const allCards = Array.from(document.querySelectorAll('a.card'));
const allSections = Array.from(document.querySelectorAll('section.group'));

searchInput.addEventListener('input', () => {
  const q = searchInput.value.trim().toLowerCase();
  let anyVisible = false;

  allSections.forEach(section => {
    let sectionHasMatch = false;
    section.querySelectorAll('a.card').forEach(card => {
      const match = card.dataset.label.toLowerCase().includes(q);
      card.style.display = match ? '' : 'none';
      if (match) sectionHasMatch = true;
    });
    section.style.display = (q === '' || sectionHasMatch) ? '' : 'none';
    if (sectionHasMatch || q === '') anyVisible = true;
  });

  document.getElementById('jumpNav').style.display = q === '' ? '' : 'none';
  noResults.style.display = anyVisible ? 'none' : 'block';
});

// ---------- digital rain background ----------
(function initRain(){
  const canvas = document.getElementById('rain');
  if (!canvas || window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const ctx = canvas.getContext('2d');
  const chars = 'جنودالخفاء01アイウエオカキクケコ'.split('');
  let cols, drops;

  function resize(){
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
    cols = Math.floor(canvas.width / 18);
    drops = Array(cols).fill(0).map(() => Math.random() * -50);
  }
  resize();
  window.addEventListener('resize', resize);

  function draw(){
    ctx.fillStyle = 'rgba(5,7,6,0.10)';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = '#39ffb0';
    ctx.font = '14px monospace';
    drops.forEach((y, i) => {
      const char = chars[Math.floor(Math.random() * chars.length)];
      ctx.fillText(char, i * 18, y * 18);
      drops[i] = (y * 18 > canvas.height && Math.random() > 0.975) ? 0 : y + 1;
    });
    requestAnimationFrame(draw);
  }
  draw();
})();